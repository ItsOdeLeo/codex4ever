/** UI-only translations. Forecast and resource state never depend on language. */
export const LANGUAGE_STORAGE_KEY='codex4ever-language';
export const DEFAULT_LANGUAGE='en';

export function supportedLanguage(value) {
  if(typeof value!=='string')return null;
  if(/^zh(?:-|$)/i.test(value))return 'zh-CN';
  if(/^en(?:-|$)/i.test(value))return 'en';
  return null;
}

export function chooseLanguage({saved,browserLanguages=[],browserLanguage}={}) {
  return supportedLanguage(saved)
    ??(Array.isArray(browserLanguages) ? browserLanguages : []).map(supportedLanguage).find(Boolean)
    ??supportedLanguage(browserLanguage)??DEFAULT_LANGUAGE;
}

