export function translate(language,source,values={}) {
  source=String(source??'');
  const pattern=uiLocale(language)==='zh-CN' ? source : english[source]??source;
  return pattern.replace(/\{(\w+)\}/g,(_,key)=>String(values[key]??`{${key}}`));
}

export const translator=(language='zh-CN')=>(source,values)=>translate(language,source,values);

/** Localize known validation/status messages without translating source posts. */
export function diagnosticText(language,message,kind='forecast') {
  if(uiLocale(language)==='zh-CN')return message;
  if(english[message])return english[message];
  const expired=message?.match(/^备用 reset (\d{4}-\d{2}-\d{2}) 已过期$/);
  if(expired)return translate(language,'备用 reset {date} 已过期',{date:expired[1]});
  if(message&&!/\p{Script=Han}/u.test(message))return message;
  return translate(language,kind==='input' ? '请检查剩余额度、刷新时间和备用到期日期。' : '预测数据暂不可用');
}
